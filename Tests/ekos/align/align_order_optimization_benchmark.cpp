/*
 * Standalone Mount Model Sort Angular Movement Benchmark
 *
 * PURPOSE
 * -------
 * The mount model wizard generates N Halton alignment points and visits them in
 * a sorted order.  The choice of sort strategy determines the total angular
 * travel on the mount axes.  This benchmark compares seven sort strategies:
 *
 *   1. Angular        -- great-circle sky distance on RA/Dec (the legacy metric).
 *                        Ignorant of mount kinematics; compresses high-Dec moves
 *                        because cos(Dec) shrinks apparent RA separation.
 *
 *   2. GEM            -- max(|delta_HA|*15, |delta_Dec|) + FLIP_PENALTY_DEG when
 *                        the move crosses the meridian (sign of HA changes).  The
 *                        base cost models simultaneous-axis travel; the penalty
 *                        models the extra time for a physical pier flip.  Adjust
 *                        FLIP_PENALTY_DEG to match your mount's flip time.
 *
 *   3. Fork           -- max(|delta_RA|*15, |delta_Dec|).  Same simultaneous-axis
 *                        model as GEM but expressed in RA instead of HA, suitable
 *                        for fork equatorial mounts that track past the meridian
 *                        without a flip.  Mathematically equivalent to GEM for a
 *                        fixed LST (|delta_RA| == |delta_HA|).
 *
 *   4. Alt/Az         -- max(|delta_Az|, |delta_Alt|).  Physical model for alt-az
 *                        mounts; uses the horizontal coordinates generated by the
 *                        Halton sampler before conversion to RA/Dec.
 *
 *   5. Pier-side      -- Two-phase GEM sort: sort east-of-meridian points, do one
 *                        explicit flip, sort west-of-meridian points.  Guarantees
 *                        exactly one pier flip for a complete model run.
 *
 *   6. Production/EQ  -- alignOrderOptimization(isAltAz=false): greedy nearest-
 *                        neighbor seeded with the GEM axis metric, then 2-opt and
 *                        Or-opt-1 local search until convergence.
 *
 *   7. Production/AA  -- alignOrderOptimization(isAltAz=true): same algorithm with
 *                        the Alt/Az axis metric.
 *
 * The cross-evaluation matrix shows total axis travel (degrees) for each sort
 * order measured under each physical metric, with deltas vs Angular baseline.
 * This reveals what happens if you use the wrong sort for your mount type, and
 * how much the production local-search improves over pure greedy.
 *
 * No KStars, Qt, or INDI headers required.
 *
 * Build (from repo root):
 *   g++ -std=c++17 -O2 \
 *       -I kstars/ekos/align \
 *       Tests/ekos/align/align_order_optimization_benchmark.cpp \
 *       kstars/ekos/align/alignorderoptimization.cpp \
 *       -o align_order_optimization_benchmark \
 *   && ./align_order_optimization_benchmark
 *
 * Fixed parameters: LST=6h, Lat=34 N, minAlt=20, nPoints=100, slewRate=3 deg/s
 */

#include "alignorderoptimization.h"
#include "haltonsequence.h"

#include <algorithm>
#include <cmath>
#include <functional>
#include <iomanip>
#include <iostream>
#include <string>
#include <vector>

using Ekos::AlignOrderPoint;
using Ekos::HaltonSequence;

static constexpr double DEG = M_PI / 180.0;

// ---- Angle helpers ---------------------------------------------------------

static double rangeHA(double ha)
{
    while (ha >  12.0) ha -= 24.0;
    while (ha < -12.0) ha += 24.0;
    return ha;
}

static double rangeRA(double ra)
{
    while (ra <   0.0) ra += 24.0;
    while (ra >= 24.0) ra -= 24.0;
    return ra;
}

static double deltaAz(double az1, double az2)
{
    double d = std::fmod(std::abs(az1 - az2), 360.0);
    return d > 180.0 ? 360.0 - d : d;
}

// ---- Coordinate conversion -------------------------------------------------

// Az/Alt -> RA/Dec (Az from North toward East, KStars convention).
static void horizontalToEquatorial(double az_deg, double alt_deg,
                                   double lst_h, double lat_deg,
                                   double &ra_h, double &dec_deg)
{
    const double az  = az_deg  * DEG;
    const double alt = alt_deg * DEG;
    const double lat = lat_deg * DEG;

    const double sin_dec = std::sin(lat) * std::sin(alt)
                         + std::cos(lat) * std::cos(alt) * std::cos(az);
    dec_deg = std::asin(std::max(-1.0, std::min(1.0, sin_dec))) / DEG;

    const double ha_rad = std::atan2(-std::sin(az) * std::cos(alt),
                                      std::sin(alt) * std::cos(lat)
                                      - std::cos(alt) * std::sin(lat) * std::cos(az));
    ra_h = rangeRA(lst_h - ha_rad / DEG / 15.0);
}

// ---- Experimental distance metrics -----------------------------------------
//
// Metric signature: (from, to) -> degrees.  LST and other parameters that are
// fixed for a given run are captured in the lambda at construction time.
// This is more flexible than the two-mode isAltAz interface in
// alignOrderOptimization, which is sufficient for production but limits
// experimentation.

using Metric = std::function<double(const AlignOrderPoint &, const AlignOrderPoint &)>;

// Haversine great-circle distance on RA/Dec.
static double metricAngular(const AlignOrderPoint &a, const AlignOrderPoint &b)
{
    const double dra = (a.ra_h - b.ra_h) * 15.0 * DEG;
    const double d1  = a.dec_deg * DEG;
    const double d2  = b.dec_deg * DEG;
    const double hav = std::pow(std::sin((d2 - d1) / 2.0), 2)
                     + std::cos(d1) * std::cos(d2) * std::pow(std::sin(dra / 2.0), 2);
    return 2.0 * std::asin(std::sqrt(std::max(0.0, std::min(1.0, hav)))) / DEG;
}

// GEM simultaneous-axis model with configurable pier-flip penalty.
// Base cost: max(|delta_HA|*15, |delta_Dec|).
// Adds flipPenaltyDeg when HA sign changes (cross-meridian move).
static Metric makeMetricGEM(double lst_h, double flipPenaltyDeg)
{
    return [lst_h, flipPenaltyDeg](const AlignOrderPoint &a, const AlignOrderPoint &b) -> double
    {
        const double haA = rangeHA(lst_h - a.ra_h);
        const double haB = rangeHA(lst_h - b.ra_h);
        double cost = std::max(std::abs(haA - haB) * 15.0,
                               std::abs(a.dec_deg - b.dec_deg));
        if (haA * haB < 0.0)
            cost += flipPenaltyDeg;
        return cost;
    };
}

// Alt/Az simultaneous-axis model: max(|delta_Az|, |delta_Alt|).
static double metricAltAz(const AlignOrderPoint &a, const AlignOrderPoint &b)
{
    return std::max(deltaAz(a.az_deg, b.az_deg), std::abs(a.alt_deg - b.alt_deg));
}

// Fork equatorial simultaneous-axis model: max(|delta_RA|*15, |delta_Dec|).
static double metricFork(const AlignOrderPoint &a, const AlignOrderPoint &b)
{
    double dra = std::abs(a.ra_h - b.ra_h);
    if (dra > 12.0) dra = 24.0 - dra;
    return std::max(dra * 15.0, std::abs(a.dec_deg - b.dec_deg));
}

// ---- Generic nearest-neighbor sort -----------------------------------------
//
// Same greedy algorithm as alignOrderOptimization but takes an
// arbitrary Metric lambda.  Also returns per-leg distances for analysis.
// Use this to experiment with new metrics before promoting them to production.

struct SortResult
{
    std::vector<int>    order;
    std::vector<double> legs;
    double              total = 0.0;
};

static SortResult nearestNeighborSort(const std::vector<AlignOrderPoint> &pts,
                                      const AlignOrderPoint &start,
                                      const Metric &metric)
{
    const int n = static_cast<int>(pts.size());
    std::vector<bool> visited(n, false);
    SortResult r;

    double best = 1e9;
    int    idx  = 0;
    for (int i = 0; i < n; i++)
    {
        double d = metric(start, pts[i]);
        if (d < best) { best = d; idx = i; }
    }
    r.order.push_back(idx);
    r.legs.push_back(best);
    r.total += best;
    visited[idx] = true;

    for (int step = 1; step < n; step++)
    {
        const AlignOrderPoint &cur = pts[r.order.back()];
        best = 1e9;
        idx  = -1;
        for (int i = 0; i < n; i++)
        {
            if (visited[i]) continue;
            double d = metric(cur, pts[i]);
            if (d < best) { best = d; idx = i; }
        }
        r.order.push_back(idx);
        r.legs.push_back(best);
        r.total += best;
        visited[idx] = true;
    }
    return r;
}

// ---- Pier-side sort (experimental) -----------------------------------------
//
// Two-phase GEM sort that guarantees exactly one pier flip:
//   1. Partition points into east-of-meridian (HA < 0) and west (HA > 0).
//   2. Nearest-neighbor sort within each half using the base axis metric.
//   3. Start with whichever half is closer to `start`, flip once, finish
//      the other half.
// The flip is recorded as a single leg of flipPenaltyDeg in the result.
static SortResult pierSideSort(const std::vector<AlignOrderPoint> &pts,
                               const AlignOrderPoint &start,
                               double lst_h,
                               double flipPenaltyDeg)
{
    std::vector<int> east, west;
    for (int i = 0; i < static_cast<int>(pts.size()); i++)
    {
        if (rangeHA(lst_h - pts[i].ra_h) >= 0.0)
            west.push_back(i);
        else
            east.push_back(i);
    }

    auto sortSubset = [&](const std::vector<int> &subset,
                          const AlignOrderPoint &from,
                          SortResult &r)
    {
        std::vector<bool> used(subset.size(), false);
        AlignOrderPoint cur = from;
        for (int step = 0; step < static_cast<int>(subset.size()); step++)
        {
            double best = 1e9;
            int    bi   = -1;
            for (int i = 0; i < static_cast<int>(subset.size()); i++)
            {
                if (used[i]) continue;
                double d = metricFork(cur, pts[subset[i]]);
                if (d < best) { best = d; bi = i; }
            }
            used[bi] = true;
            r.order.push_back(subset[bi]);
            r.legs.push_back(best);
            r.total += best;
            cur = pts[subset[bi]];
        }
    };

    auto nearestInSubset = [&](const std::vector<int> &subset) -> double {
        double best = 1e9;
        for (int i : subset)
            best = std::min(best, metricFork(start, pts[i]));
        return best;
    };

    const bool startWest = west.empty() ||
                           (!east.empty() &&
                            nearestInSubset(west) > nearestInSubset(east));
    const std::vector<int> &first  = startWest ? west : east;
    const std::vector<int> &second = startWest ? east : west;

    SortResult r;

    sortSubset(first, start, r);

    if (!second.empty())
    {
        r.legs.push_back(flipPenaltyDeg);
        r.total += flipPenaltyDeg;
        r.order.push_back(-1);  // sentinel: pier flip event

        const AlignOrderPoint &afterFlip = r.order.size() > 1
                                          ? pts[r.order[r.order.size() - 2]]
                                          : start;
        sortSubset(second, afterFlip, r);
    }

    return r;
}

// ---- Cross-evaluation ------------------------------------------------------
//
// Compute total travel along a pre-determined visit order under any metric.
// Sentinel -1 in the order means a pier flip; it always costs flipPenaltyDeg
// and does not change the current position.
static double crossEvaluate(const std::vector<int> &order,
                             const std::vector<AlignOrderPoint> &pts,
                             const AlignOrderPoint &start,
                             const Metric &metric,
                             double flipPenaltyDeg)
{
    double total              = 0.0;
    const AlignOrderPoint *cur = &start;
    for (int idx : order)
    {
        if (idx == -1)
            total += flipPenaltyDeg;
        else
        {
            total += metric(*cur, pts[idx]);
            cur = &pts[idx];
        }
    }
    return total;
}

// Count meridian crossings.  Sentinel -1 = explicit flip; HA sign change
// between consecutive real points = implicit flip (but not right after a
// sentinel, since that transition is already counted as the flip).
static int countFlips(const std::vector<int> &order,
                      const std::vector<AlignOrderPoint> &pts,
                      const AlignOrderPoint &start,
                      double lst_h)
{
    int  flips         = 0;
    bool afterSentinel = false;
    const AlignOrderPoint *prev = &start;
    for (int idx : order)
    {
        if (idx == -1)
        {
            flips++;
            afterSentinel = true;
        }
        else
        {
            if (!afterSentinel)
            {
                double haPrev = rangeHA(lst_h - prev->ra_h);
                double haCur  = rangeHA(lst_h - pts[idx].ra_h);
                if (haPrev * haCur < 0.0)
                    flips++;
            }
            afterSentinel = false;
            prev = &pts[idx];
        }
    }
    return flips;
}

// ---- Wrap alignOrderOptimization output into SortResult -----------------------
//
// alignOrderOptimization returns a bare order vector; this helper computes the
// per-leg distances under a given metric so it can slot into the cross-eval
// matrix alongside the greedy results.
static SortResult productionSortResult(const std::vector<AlignOrderPoint> &pts,
                                       const AlignOrderPoint &start,
                                       bool isAltAz,
                                       double lst_h,
                                       const Metric &metric,
                                       double flipPenaltyDeg = 0.0)
{
    SortResult r;
    r.order = Ekos::alignOrderOptimization(pts, start, isAltAz, lst_h, flipPenaltyDeg);
    const AlignOrderPoint *prev = &start;
    for (int idx : r.order)
    {
        double d = metric(*prev, pts[idx]);
        r.legs.push_back(d);
        r.total += d;
        prev = &pts[idx];
    }
    return r;
}

// ---- Output helpers --------------------------------------------------------

static void printTime(double sec)
{
    std::cout << static_cast<int>(sec) / 60 << "m"
              << std::setw(2) << std::setfill('0') << static_cast<int>(sec) % 60 << "s"
              << std::setfill(' ');
}

static void printResult(const std::string &name, const SortResult &r, double slewRate)
{
    const double timeSec = r.total / slewRate;
    std::cout << "\n=== " << name << " ===\n";

    std::cout << "Order:";
    for (int i = 0; i < static_cast<int>(r.order.size()); i++)
    {
        if (i % 10 == 0) std::cout << "\n  ";
        std::cout << std::setw(3) << r.order[i];
        if (i + 1 < static_cast<int>(r.order.size())) std::cout << " ->";
    }

    std::cout << "\nLegs (deg):";
    for (int i = 0; i < static_cast<int>(r.legs.size()); i++)
    {
        if (i % 10 == 0) std::cout << "\n  ";
        std::cout << std::fixed << std::setprecision(1) << std::setw(6) << r.legs[i];
    }

    std::cout << "\nTotal: " << std::fixed << std::setprecision(1) << r.total
              << " deg  =  ";
    printTime(timeSec);
    std::cout << "\n";
}

// ---- Main ------------------------------------------------------------------

int main()
{
    constexpr double LST_H            = 6.0;
    constexpr double LAT_DEG          = 34.0;
    constexpr double MIN_ALT          = 20.0;
    constexpr double MAX_ALT          = 85.0;
    constexpr double MAX_ABS_DEC      = 80.0;
    constexpr int    N_POINTS         = 100;
    constexpr double SLEW_RATE        = 3.0;    // deg/s
    constexpr double FLIP_PENALTY_DEG = Ekos::ALIGN_FLIP_PENALTY_DEG;

    std::cout << "Mount Model Sort Travel Cost Test\n";
    std::cout << "Parameters: LST=" << LST_H << "h  Lat=" << LAT_DEG
              << " N  minAlt=" << MIN_ALT << " deg  nPoints=" << N_POINTS
              << "  slewRate=" << SLEW_RATE << " deg/s"
              << "  flipPenalty=" << FLIP_PENALTY_DEG << " deg ("
              << FLIP_PENALTY_DEG / SLEW_RATE << "s)\n";

    // Generate N_POINTS Halton points in AltAz space (mirrors MountModel::generateHaltonPoints).
    const double sinMin = std::sin(MIN_ALT * DEG);
    const double sinMax = std::sin(MAX_ALT * DEG);

    std::vector<AlignOrderPoint> points;
    points.reserve(N_POINTS);

    HaltonSequence haltonAz(2);
    HaltonSequence haltonAlt(3);
    const int maxCandidates = std::max(N_POINTS * 10, 200);
    for (int i = 0; i < maxCandidates && static_cast<int>(points.size()) < N_POINTS; i++)
    {
        const double az  = haltonAz.next() * 360.0;
        const double alt = std::asin(sinMin + haltonAlt.next() * (sinMax - sinMin)) / DEG;

        double ra_h, dec_deg;
        horizontalToEquatorial(az, alt, LST_H, LAT_DEG, ra_h, dec_deg);
        if (std::abs(dec_deg) > MAX_ABS_DEC)
            continue;

        AlignOrderPoint p;
        p.ra_h    = ra_h;
        p.dec_deg = dec_deg;
        p.az_deg  = az;
        p.alt_deg = alt;
        points.push_back(p);
    }

    std::cout << "Generated " << points.size() << " points\n";

    std::cout << "\n Idx   RA(h)   Dec(d)    Az(d)   Alt(d)    HA(h)\n";
    for (int i = 0; i < static_cast<int>(points.size()); i++)
    {
        const auto &p = points[i];
        std::cout << std::setw(4) << i
                  << std::fixed << std::setprecision(2)
                  << "  " << std::setw(6) << p.ra_h
                  << "  " << std::setw(7) << p.dec_deg
                  << "  " << std::setw(7) << p.az_deg
                  << "  " << std::setw(7) << p.alt_deg
                  << "  " << std::setw(7) << rangeHA(LST_H - p.ra_h) << "\n";
    }

    // Start position: HA=0, Dec=LAT_DEG (meridian at latitude).
    AlignOrderPoint startPos;
    startPos.ra_h    = rangeRA(LST_H);
    startPos.dec_deg = LAT_DEG;
    startPos.az_deg  = 0.0;
    startPos.alt_deg = 90.0 - std::abs(LAT_DEG - LAT_DEG);  // ~56 deg

    std::cout << "\nStart: RA=" << startPos.ra_h << "h  Dec=" << startPos.dec_deg
              << "d  HA=0.00h  Alt~" << startPos.alt_deg << "d\n";

    const Metric gemMetric = makeMetricGEM(LST_H, FLIP_PENALTY_DEG);

    // Run all seven scenarios.
    const auto r1 = nearestNeighborSort(points, startPos, metricAngular);
    const auto r2 = nearestNeighborSort(points, startPos, gemMetric);
    const auto r3 = nearestNeighborSort(points, startPos, metricAltAz);
    const auto r4 = nearestNeighborSort(points, startPos, metricFork);
    const auto r5 = pierSideSort(points, startPos, LST_H, FLIP_PENALTY_DEG);
    // Production sort: greedy + 2-opt + Or-opt-1, measured under its native metric.
    const auto r6 = productionSortResult(points, startPos, false, LST_H, gemMetric, FLIP_PENALTY_DEG);
    const auto r7 = productionSortResult(points, startPos, true,  LST_H, metricAltAz);

    printResult("Angular Distance (sky great-circle)", r1, SLEW_RATE);
    printResult("GEM: max(|dHA|*15, |dDec|) + flip",  r2, SLEW_RATE);
    printResult("Alt/Az: max(|dAz|, |dAlt|)",          r3, SLEW_RATE);
    printResult("Fork: max(|dRA|*15, |dDec|)",         r4, SLEW_RATE);
    printResult("Pier-side (two-phase, one flip)",     r5, SLEW_RATE);
    printResult("Production EQ (greedy+2opt+oropt1)",  r6, SLEW_RATE);
    printResult("Production AA (greedy+2opt+oropt1)",  r7, SLEW_RATE);

    // Cross-evaluation matrix.
    struct Scenario   { std::string name; const SortResult *r; };
    struct MeasureDef { std::string name; Metric fn; };

    const Scenario scenarios[] = {
        {"Angular sort",    &r1},
        {"GEM sort",        &r2},
        {"Alt/Az sort",     &r3},
        {"Fork sort",       &r4},
        {"Pier-side sort",  &r5},
        {"Production EQ",   &r6},
        {"Production AA",   &r7},
    };
    const MeasureDef measures[] = {
        {"Angular (deg)",    metricAngular},
        {"GEM axis (deg)",   gemMetric    },
        {"AltAz axis (deg)", metricAltAz  },
        {"Fork axis (deg)",  metricFork   },
    };

    const int nMeasures  = static_cast<int>(sizeof(measures)  / sizeof(measures[0]));
    const int nScenarios = static_cast<int>(sizeof(scenarios) / sizeof(scenarios[0]));

    std::vector<double> baseline(nMeasures);
    for (int mi = 0; mi < nMeasures; mi++)
        baseline[mi] = crossEvaluate(r1.order, points, startPos,
                                     measures[mi].fn, FLIP_PENALTY_DEG);

    auto fmtTime = [](double sec) -> std::string {
        bool neg = sec < 0;
        int s = static_cast<int>(std::abs(sec));
        char buf[16];
        std::snprintf(buf, sizeof(buf), "%s%dm%02ds", neg ? "-" : "+", s / 60, s % 60);
        return buf;
    };

    auto fmtCell = [&](double deg, double baseDeg, bool isBaseline) -> std::string {
        double t  = deg / SLEW_RATE;
        double dt = (deg - baseDeg) / SLEW_RATE;
        char buf[48];
        if (isBaseline)
            std::snprintf(buf, sizeof(buf), "%5.0fdeg/%dm%02ds (base)",
                          deg, static_cast<int>(t) / 60, static_cast<int>(t) % 60);
        else
            std::snprintf(buf, sizeof(buf), "%5.0fdeg/%dm%02ds (%s)",
                          deg, static_cast<int>(t) / 60, static_cast<int>(t) % 60,
                          fmtTime(dt).c_str());
        return buf;
    };

    std::cout << "\n=== Cross-Evaluation: travel cost of each sort order under each physical metric ===\n";
    std::cout << "Cells: total_deg / time (delta vs Angular sort baseline)\n\n";

    const int colW     = 28;
    const int flipColW = 7;
    std::cout << std::left << std::setw(16) << "Sort \\ Metric";
    std::cout << "  " << std::setw(flipColW) << "Flips";
    for (int mi = 0; mi < nMeasures; mi++)
        std::cout << "  " << std::setw(colW) << measures[mi].name;
    std::cout << "\n" << std::string(16 + flipColW + 2 + nMeasures * (colW + 2), '-') << "\n";

    for (int si = 0; si < nScenarios; si++)
    {
        auto &sc = scenarios[si];
        int flips = countFlips(sc.r->order, points, startPos, LST_H);
        std::cout << std::left << std::setw(16) << sc.name;
        std::cout << "  " << std::setw(flipColW) << flips;
        for (int mi = 0; mi < nMeasures; mi++)
        {
            double total = crossEvaluate(sc.r->order, points, startPos,
                                         measures[mi].fn, FLIP_PENALTY_DEG);
            std::cout << "  " << std::setw(colW) << fmtCell(total, baseline[mi], si == 0);
        }
        std::cout << "\n";
    }

    std::cout << "\nBest sort per physical metric (lowest cost):\n";
    for (int mi = 0; mi < nMeasures; mi++)
    {
        double best = 1e9;
        const std::string *bestName = nullptr;
        for (int si = 0; si < nScenarios; si++)
        {
            double total = crossEvaluate(scenarios[si].r->order, points, startPos,
                                         measures[mi].fn, FLIP_PENALTY_DEG);
            if (total < best) { best = total; bestName = &scenarios[si].name; }
        }
        std::cout << "  " << std::left << std::setw(22) << measures[mi].name
                  << " -> " << *bestName << "  ("
                  << fmtCell(best, baseline[mi], bestName == &scenarios[0].name) << ")\n";
    }

    return 0;
}
